import os from 'node:os';
import fs from 'node:fs';
import path from 'node:path';
import { createApp } from './app.js';
import config from './config.js';
import { logger } from './lib/http.js';
import { llmStatus } from './services/chat.js';
import { stats as auditStats } from './services/audit.js';
import { connectDB } from './db.js';

await connectDB();
const app = createApp();
const server = app.listen(config.port, config.host, () => {
  const addresses = localAddresses();
  logger.info('JeevanSetu API listening', {
    port: config.port,
    env: config.env,
    pid: process.pid,
    node: process.version
  });

  process.stdout.write('\n  JeevanSetu backend ready\n\n');
  process.stdout.write(`  Local    http://localhost:${config.port}\n`);
  for (const address of addresses) {
    process.stdout.write(`  Network  http://${address}:${config.port}\n`);
  }
  process.stdout.write(`  Health   http://localhost:${config.port}/api/health\n\n`);

  const llm = llmStatus();
  process.stdout.write(`  Safety engine  deterministic v${config.triage.engineVersion} (always on)\n`);
  process.stdout.write(`  LLM layer      ${llm.enabled ? `${llm.model} — phrasing only, cannot change the risk level` : 'not configured — replies generated by the built-in engine'}\n`);
  process.stdout.write(`  Frontend       ${hasFrontendBuild() ? 'serving dist/ (run "npm run build" to refresh)' : 'no build found — run "npm run build", or use "npm run dev" for hot reload'}\n`);
  process.stdout.write(`  Data dir       ${config.storage.dir}\n`);
  process.stdout.write(`  Audit trail    ${auditStats().totalEvents} hash-chained events\n\n`);

  if (config.host === '0.0.0.0') {
    process.stdout.write(
      '  Note: bound to all interfaces, so devices on the same network can reach this API.\n' +
      '  Data is synthetic demo data. Set HOST=127.0.0.1 to restrict it to this machine.\n\n'
    );
  }
});

function hasFrontendBuild() {
  return fs.existsSync(path.join(config.clientDist, 'index.html'));
}

function localAddresses() {
  const out = [];
  const ifaces = os.networkInterfaces();
  for (const list of Object.values(ifaces)) {
    for (const iface of list || []) {
      if (iface.family === 'IPv4' && !iface.internal) out.push(iface.address);
    }
  }
  return out;
}

server.on('error', (error) => {
  if (error.code === 'EADDRINUSE') {
    process.stderr.write(
      `\n  Port ${config.port} is already in use.\n` +
      `  Stop the other process, or start with a different one:\n` +
      `    PORT=3002 npm start\n\n`
    );
    process.exit(1);
  }
  logger.error('server error', { message: error.message, code: error.code });
  process.exit(1);
});

// --- Graceful shutdown -----------------------------------------------------
// Stop accepting connections, let in-flight requests finish, then exit. A hard
// kill mid-write could otherwise leave the audit JSONL with a torn last line.

let shuttingDown = false;

function shutdown(signal) {
  if (shuttingDown) return;
  shuttingDown = true;
  logger.info('shutting down', { signal });

  const forceExit = setTimeout(() => {
    logger.error('forced shutdown after timeout');
    process.exit(1);
  }, 10_000);
  forceExit.unref();

  server.close(() => {
    clearTimeout(forceExit);
    logger.info('server closed');
    process.exit(0);
  });
}

for (const signal of ['SIGINT', 'SIGTERM']) {
  process.on(signal, () => shutdown(signal));
}

process.on('unhandledRejection', (reason) => {
  logger.error('unhandled promise rejection', { reason: reason instanceof Error ? reason.stack : String(reason) });
});

process.on('uncaughtException', (error) => {
  logger.error('uncaught exception', { message: error.message, stack: error.stack });
  shutdown('uncaughtException');
});

export default server;
